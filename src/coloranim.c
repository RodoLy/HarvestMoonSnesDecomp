/*
 * coloranim.c — colour animations (palette cycling): water, lights,
 * flowers... 16 channels change one palette colour each, step by step.
 *
 * A channel ($42 + 3 n: a 24-bit pointer; $014A + n: frames left of this
 * step; $015A + n: the colour; $016A + n: the palette row) walks a list of
 * steps of 3 bytes: the colour (a word) and how many frames it stays (a
 * byte). $FFFF ends the list; $FFFE <pointer 24> jumps (a loop).
 *
 *   UNK_SetPointer42   start channel X with the list at [$72] (colour A,
 *                      row Y)
 *   UNK_BigLoop        every frame: advance every channel and, if one ran,
 *                      send the palette ($7F:0900) to the console
 *   Zeroes...          stop channels
 *   CallIndexedSubrutines  starts the animations of the map for this part
 *                      of the day: Subrutines_Table ($80:BEEC) has 6 words
 *                      per map (5 parts of the day, then a word that, when
 *                      not $FFFF, means "only in autumn and winter")
 *   SUB_80C36C...      the 51 routines of that table: each starts some
 *                      channels (the lists are in bank $80)
 */
#include "hm_decomp.h"
#include "hm_ram.h"   /* from the recompilation project */

#define DELAY   0x014A
#define COLOUR  0x015A
#define ROW     0x016A

static uint32_t db_addr(const HmRegs *r, uint16_t a) { return (uint32_t)r->db << 16 | a; }
static uint16_t dp16(uint8_t *ram, const HmRegs *r, unsigned a) { return hm_dp_r16(ram, r, a); }
static void set16(uint8_t *ram, const HmRegs *r, unsigned a, uint16_t v) { hm_dp_w16(ram, r, a, v); }
static void push16(uint8_t *ram, HmRegs *r, uint16_t v)
{
  hm_push8(ram, r, (uint8_t)(v >> 8));
  hm_push8(ram, r, (uint8_t)v);
}
static uint16_t pull16(uint8_t *ram, HmRegs *r)
{
  uint16_t lo = hm_pull8(ram, r);
  return (uint16_t)(lo | hm_pull8(ram, r) << 8);
}
/* TYA; STA $7E; ASL; CLC; ADC $7E; TAX: the channel's pointer offset */
static uint16_t times3(uint8_t *ram, HmRegs *r, uint16_t n)
{
  set16(ram, r, 0x7E, n);
  uint32_t s = (uint32_t)(uint16_t)(n << 1) + n;
  r->c = s > 0xFFFF;
  r->a = r->x = (uint16_t)s;
  return r->x;
}

/* UNK_SetPointer42 ($80:8E48, JSL, RTL; 8-bit A, X, Y) */
void hm_UNK_SetPointer42(uint8_t *ram, HmRegs *r)
{
  hm_bus_wr8(ram, db_addr(r, (uint16_t)(COLOUR + r->x)), (uint8_t)r->a);
  r->a = (uint16_t)((r->a & 0xFF00) | (uint8_t)r->y);   /* TYA (8 bits) */
  hm_bus_wr8(ram, db_addr(r, (uint16_t)(ROW + r->x)), (uint8_t)r->y);
  hm_bus_wr8(ram, db_addr(r, (uint16_t)(DELAY + r->x)), 0);
  uint16_t n = r->x;                                    /* TXA (16-bit A) */
  set16(ram, r, 0x7E, n);
  uint32_t s = (uint32_t)(uint16_t)(n << 1) + n;
  r->c = s > 0xFFFF;
  r->x = (uint8_t)s;                                    /* TAX (8-bit X) */
  r->a = dp16(ram, r, 0x72);
  set16(ram, r, 0x42 + r->x, r->a);
  r->a = (uint16_t)((r->a & 0xFF00) | *hm_dp(ram, r, 0x74));
  *hm_dp(ram, r, 0x44 + r->x) = *hm_dp(ram, r, 0x74);
}

/* ─────────────────────────────────────────────────────────────────────────
 * UNK_BigLoop ($80:8E69), every frame. Channels 0-3 run only while it
 * rains or snows ($0196 bits 1 / 3); from channel 4 on, the first empty
 * channel ends the loop, so they must be used in order.
 * ───────────────────────────────────────────────────────────────────────── */
void hm_UNK_BigLoop(uint8_t *ram, HmRegs *r)
{
  *hm_dp(ram, r, 0x92) = 0;
  *hm_dp(ram, r, 0x93) = 0;
  r->y = 0;
  r->a = hm_bus_rd16(ram, db_addr(r, 0x0196)) & 0x000A;
  if (!r->a) r->y = 4;
  for (;;) {
    uint16_t x = times3(ram, r, r->y);
    r->a = dp16(ram, r, 0x42 + x);
    bool set = r->a != 0;
    if (!set) {
      r->a = (uint16_t)((r->a & 0xFF00) | *hm_dp(ram, r, 0x44 + x));
      set = *hm_dp(ram, r, 0x44 + x) != 0;
    }
    if (!set) {
      r->c = r->y >= 4;
      if (r->c) break;                                  /* the end of the channels */
      goto next;
    }
    r->a = (uint16_t)((r->a & 0xFF00) | 1);
    *hm_dp(ram, r, 0x93) = 1;
    push16(ram, r, r->y);                               /* PHY */
    set16(ram, r, 0x72, dp16(ram, r, 0x42 + x));
    *hm_dp(ram, r, 0x74) = *hm_dp(ram, r, 0x44 + x);
    r->a = (uint16_t)((dp16(ram, r, 0x42 + x) & 0xFF00) | *hm_dp(ram, r, 0x44 + x));
    r->a = hm_bus_rd16(ram, hm_dp_long(ram, r, 0x72, 0));
    r->c = r->a >= 0xFFFF;
    if (r->a == 0xFFFF) {                               /* the end of the list */
      set16(ram, r, 0x42 + x, 0);
      *hm_dp(ram, r, 0x44 + x) = 0;
    } else {
      r->c = r->a >= 0xFFFE;
      if (r->a == 0xFFFE) {                             /* a jump */
        r->y = 2;
        r->a = hm_bus_rd16(ram, hm_dp_long(ram, r, 0x72, 2));
        set16(ram, r, 0x42 + x, r->a);
        r->y = 4;
        uint8_t bank = hm_bus_rd8(ram, hm_dp_long(ram, r, 0x72, 4));
        r->a = (uint16_t)((r->a & 0xFF00) | bank);
        *hm_dp(ram, r, 0x44 + x) = bank;
        set16(ram, r, 0x72, dp16(ram, r, 0x42 + x));
        *hm_dp(ram, r, 0x74) = bank;
        r->a = (uint16_t)((dp16(ram, r, 0x42 + x) & 0xFF00) | bank);
      }
    }
    r->y = pull16(ram, r);                              /* PLY; TYX */
    r->x = r->y;
    uint8_t wait = hm_bus_rd8(ram, db_addr(r, (uint16_t)(DELAY + r->x)));
    r->a = (uint16_t)((r->a & 0xFF00) | wait);
    if (wait) {                                         /* still waiting */
      hm_bus_wr8(ram, db_addr(r, (uint16_t)(DELAY + r->x)), (uint8_t)(wait - 1));
      goto next;
    }
    push16(ram, r, r->y);                               /* PHY */
    uint8_t row = hm_bus_rd8(ram, db_addr(r, (uint16_t)(ROW + r->x)));
    push16(ram, r, row);                                /* LDA #0; XBA; LDA; PHA */
    uint8_t col = hm_bus_rd8(ram, db_addr(r, (uint16_t)(COLOUR + r->x)));
    push16(ram, r, col);
    r->a = hm_bus_rd16(ram, hm_dp_long(ram, r, 0x72, 0));
    r->x = pull16(ram, r);                              /* PLX; PLY */
    r->y = pull16(ram, r);
    hm_jsl(ram, r, 0x8EEE, 0x80);
    hm_SUB_80916F(ram, r);                              /* the new colour */
    hm_rtl(ram, r);
    r->y = pull16(ram, r);                              /* PLY; PHY; TYX */
    push16(ram, r, r->y);
    r->x = r->y;
    uint8_t frames = hm_bus_rd8(ram, hm_dp_long(ram, r, 0x72, 2));
    r->a = (uint16_t)((r->a & 0xFF00) | frames);
    hm_bus_wr8(ram, db_addr(r, (uint16_t)(DELAY + r->x)), frames);
    r->y = pull16(ram, r);
    x = times3(ram, r, r->y);
    uint32_t p = (uint32_t)dp16(ram, r, 0x42 + x) + 3;  /* the next step */
    set16(ram, r, 0x42 + x, (uint16_t)p);
    uint16_t b = (uint16_t)(*hm_dp(ram, r, 0x44 + x) + (p > 0xFFFF));
    r->c = b > 0xFF;
    r->a = (uint16_t)((p & 0xFF00) | (uint8_t)b);
    *hm_dp(ram, r, 0x44 + x) = (uint8_t)b;
  next:
    times3(ram, r, r->y);
    r->y = (uint16_t)(r->y + 1);
    r->c = r->y >= 0x10;
    if (r->y == 0x10) break;
  }
  if (!*hm_dp(ram, r, 0x93)) {
    r->a = (uint16_t)(r->a & 0xFF00);
    return;
  }
  /* send the palette: channel 5, to $2122 (CGRAM), from $7F:0900 */
  *hm_dp(ram, r, 0x27) = 5;
  *hm_dp(ram, r, 0x29) = 0x22;
  r->y = 0x0100;
  r->x = 0;
  set16(ram, r, 0x72, 0x0900);
  *hm_dp(ram, r, 0x74) = 0x7F;
  r->a = 0x097F;
  hm_jsl(ram, r, 0x8F50, 0x80);
  hm_AddProgrammedDMA(ram, r);
  hm_rtl(ram, r);
}

/* Zeroes42Pointers ($80:8FAB): stop all 16 channels; ZeroesPartial42Pointers
 * ($80:8F92): from channel Y on (Y must be below 16, or it goes round
 * 65536 times); ZeroesOne42Pointer ($80:8F82): channel A. */
static void stop_from(uint8_t *ram, HmRegs *r, uint16_t y)
{
  do {
    uint16_t x = times3(ram, r, y);
    set16(ram, r, 0x42 + x, 0);
    *hm_dp(ram, r, 0x44 + x) = 0;
    y = (uint16_t)(y + 1);
    r->c = y >= 0x10;
  } while (y != 0x10);
  r->y = y;
}
void hm_Zeroes42Pointers(uint8_t *ram, HmRegs *r) { stop_from(ram, r, 0); }
void hm_ZeroesPartial42Pointers(uint8_t *ram, HmRegs *r) { stop_from(ram, r, r->y); }
void hm_ZeroesOne42Pointer(uint8_t *ram, HmRegs *r)
{
  uint16_t x = times3(ram, r, r->a);
  set16(ram, r, 0x42 + x, 0);
  *hm_dp(ram, r, 0x44 + x) = 0;
}

/* ─────────────────────────────────────────────────────────────────────────
 * The 51 routines of Subrutines_Table: each starts some channels. One line
 * per channel: the list (24-bit), the colour, the row, the channel... as
 * UNK_SetPointer42 takes them, and the JSL's return address.
 * ───────────────────────────────────────────────────────────────────────── */
typedef struct Start { uint16_t list; uint8_t bank, colour, channel, row; uint16_t ret; } Start;

static void start_all(uint8_t *ram, HmRegs *r, const Start *s, unsigned n)
{
  for (unsigned i = 0; i < n; i++) {
    r->a = s[i].list;                                   /* REP #$20; SEP #$10 */
    set16(ram, r, 0x72, s[i].list);
    r->a = (uint16_t)((s[i].list & 0xFF00) | s[i].bank);
    *hm_dp(ram, r, 0x74) = s[i].bank;
    r->a = (uint16_t)((s[i].list & 0xFF00) | s[i].colour);
    r->x = s[i].channel;
    r->y = s[i].row;
    hm_jsl(ram, r, s[i].ret, 0x80);
    hm_UNK_SetPointer42(ram, r);
    hm_rtl(ram, r);
  }
}
