static const Pair *s_table;
static size_t s_n;

void i18n_set(const char *code)
{
  if (code && !strcmp(code, "es")) { s_table = kEs; s_n = sizeof kEs / sizeof kEs[0]; }
  else if (code && !strcmp(code, "it")) { s_table = kIt; s_n = sizeof kIt / sizeof kIt[0]; }
  else { s_table = NULL; s_n = 0; }
}

const char *T(const char *english)
{
  for (size_t i = 0; i < s_n; i++) if (!strcmp(s_table[i].en, english)) return s_table[i].tr;
  return english;
}
